const source = process.argv[2];
if (!source) {
  console.error("Usage: node tools/build-icons.mjs <path to lucide-static/icons>");
  process.exit(1);
}

const symbols = [];
const missing = [];
for (const [name, lucide] of Object.entries(ICONS)) {
  let svg;
  try {
    svg = readFileSync(join(source, lucide + ".svg"), "utf8");
  } catch {
    missing.push(`${name} (${lucide})`);
    continue;
  }
  // Keep only the drawing commands; the stroke settings live on <symbol>.
  const inner = svg
    .replace(/<!--[\s\S]*?-->/g, "")
    .replace(/<svg[\s\S]*?>/, "")
    .replace(/<\/svg>\s*$/, "")
    .replace(/\s+/g, " ")
    .trim();
  symbols.push(`<symbol id="${name}" viewBox="0 0 24 24">${inner}</symbol>`);
}

if (missing.length) {
  console.error("Missing Lucide icons: " + missing.join(", "));
  process.exit(1);
}

const sprite =
  `<!-- Icons: Lucide (https://lucide.dev), ISC licence. Generated by tools/build-icons.mjs. -->\n` +
  `<svg xmlns="http://www.w3.org/2000/svg" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">\n` +
  symbols.join("\n") +
  `\n</svg>\n`;

const out = join(dirname(fileURLToPath(import.meta.url)), "..", "ui", "img", "icons.svg");
writeFileSync(out, sprite);
console.log(`Wrote ${symbols.length} icons to ${out}`);
